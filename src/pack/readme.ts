import type { Manifest } from '../core/manifest';

/** 分区清单：文件名对齐，后面跟条目数 */
function sectionLines(manifest: Manifest, entryWord: string): string {
  const lines = manifest.sections.map(
    section => `  ${section.file.padEnd(20)}${section.entries} ${entryWord}`,
  );
  return lines.length > 0 ? lines.join('\n') : '  -';
}

/**
 * 包内给人看的说明：目录结构与手工还原的边界。
 */
export function readmeText(manifest: Manifest): string {
  const selfRestore = manifest.options.selfRestore === true;
  const zh = chinesePart(manifest, selfRestore);
  const en = englishPart(manifest, selfRestore);
  return [zh, dividerFor(zh, en), en, ''].join('\n');
}

/**
 * 分隔线的宽度取两段里最长的一行。
 *
 * 定长写死会随说明改长而变短，比正文窄的分隔线看着像正文的一部分。
 * 按内容算一次即可，两段都已生成。
 */
function dividerFor(...parts: string[]): string {
  let width = 0;
  for (const part of parts) {
    for (const line of part.split('\n')) width = Math.max(width, line.length);
  }
  return '-'.repeat(width);
}

